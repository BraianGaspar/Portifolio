const contactForm = document.getElementById('contactForm');
if (contactForm) {
  contactForm.addEventListener('submit', async function (e) {
    e.preventDefault();

    const sendBtn = document.getElementById('sendBtn');
    const feedback = document.getElementById('formFeedback');
    const originalText = sendBtn.innerHTML;

    const assunto = document.getElementById('assunto').value;
    const mensagem = document.getElementById('mensagem').value;

    if (!assunto) {
      feedback.innerHTML = translations[currentLang].form_error;
      feedback.className = 'feedback error';
      return;
    }

    if (!mensagem) {
      feedback.innerHTML = translations[currentLang].form_error_msg;
      feedback.className = 'feedback error';
      return;
    }

    sendBtn.disabled = true;
    sendBtn.innerHTML = translations[currentLang].form_sending;
    feedback.innerHTML = '';

    try {
      const texto = `*Novo contato do Portfólio!*%0A%0A*Assunto:* ${assunto}%0A*Mensagem:* ${mensagem}%0A%0A*Responder para:* braian_gaspar@hotmail.com`;
      const whatsappUrl = `https://wa.me/5545988353553?text=${texto}`;

      window.open(whatsappUrl, '_blank');

      feedback.innerHTML = translations[currentLang].form_success;
      feedback.className = 'feedback success';

      contactForm.reset();
    } catch (error) {
      feedback.innerHTML = translations[currentLang].form_error_whatsapp;
      feedback.className = 'feedback error';
    } finally {
      setTimeout(() => {
        sendBtn.disabled = false;
        sendBtn.innerHTML = translations[currentLang].form_btn;
      }, 3000);
    }
  });
}

// ========== EFEITO DE DIGITAÇÃO (opcional) ==========
const titles = [
  'Desenvolvedor Full Stack',
  'PHP • Node.js • Flutter',
  'Engenheiro de Software',
  'Criador de Soluções',
];

let titleIndex = 0;
let charIndex = 0;
let isDeleting = false;
const heroTitle = document.querySelector('.hero h2');

if (heroTitle && titles.length > 0) {
  function typeEffect() {
    const currentTitle = titles[titleIndex];

    if (isDeleting) {
      heroTitle.textContent = currentTitle.substring(0, charIndex - 1);
      charIndex--;
    } else {
      heroTitle.textContent = currentTitle.substring(0, charIndex + 1);
      charIndex++;
    }

    if (!isDeleting && charIndex === currentTitle.length) {
      isDeleting = true;
      setTimeout(typeEffect, 2000);
      return;
    }

    if (isDeleting && charIndex === 0) {
      isDeleting = false;
      titleIndex = (titleIndex + 1) % titles.length;
      setTimeout(typeEffect, 500);
      return;
    }

    const speed = isDeleting ? 50 : 100;
    setTimeout(typeEffect, speed);
  }

  // typeEffect(); // Descomente para ativar o efeito de digitação
}
