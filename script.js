let currentLang = 'pt';

function updateLanguage() {
  // Atualizar elementos com data-key
  const elements = document.querySelectorAll('[data-key]');
  elements.forEach((el) => {
    const key = el.getAttribute('data-key');
    if (translations[currentLang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[currentLang][key];
      } else if (el.tagName === 'BUTTON' && el.id !== 'sendBtn') {
        el.innerHTML = translations[currentLang][key];
      } else {
        el.innerHTML = translations[currentLang][key];
      }
    }
  });

  // Marcar idioma ativo no seletor
  document.querySelectorAll('.lang-option').forEach((btn) => {
    const active = btn.dataset.lang === currentLang;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });
  document.documentElement.lang = { pt: 'pt-br', en: 'en', es: 'es' }[currentLang];

  // Atualizar textos especiais
  updateSpecialTexts();
}

function updateSpecialTexts() {
  // Hero
  const heroTitle = document.querySelector('.hero h1');
  const heroSubtitle = document.querySelector('.hero h2');
  const heroDesc = document.querySelector('.hero p');
  const heroBtn = document.querySelector('.hero .btn');

  if (heroTitle) heroTitle.innerHTML = translations[currentLang].hero_title;
  if (heroSubtitle) heroSubtitle.innerHTML = translations[currentLang].hero_subtitle;
  if (heroDesc) heroDesc.innerHTML = translations[currentLang].hero_description;
  if (heroBtn) heroBtn.innerHTML = translations[currentLang].hero_btn;

  // Info rápida
  const infoDivs = document.querySelectorAll('.info-rapida div');
  if (infoDivs.length >= 5) {
    infoDivs[0].innerHTML = `<span>📍</span> ${translations[currentLang].location}`;
    infoDivs[1].innerHTML = `<span>📞</span> ${translations[currentLang].phone}`;
    infoDivs[2].innerHTML = `<span>🎂</span> ${translations[currentLang].age}`;
    infoDivs[3].innerHTML = `<span>🚗</span> ${translations[currentLang].cnh}`;
    infoDivs[4].innerHTML = `<span>🌐</span> ${translations[currentLang].english}`;
  }

  // Botão do formulário
  const formBtn = document.getElementById('sendBtn');
  if (formBtn && !formBtn.disabled) {
    formBtn.innerHTML = translations[currentLang].form_btn;
  }

  // Footer
  const footerFirst = document.querySelector('footer p:first-child');
  const footerSecond = document.querySelector('footer p:last-child');
  if (footerFirst) {
    footerFirst.innerHTML = `© ${new Date().getFullYear()} Braian Gaspar da Rosa | ${translations[currentLang].footer_text}`;
  }
  if (footerSecond) {
    footerSecond.innerHTML = translations[currentLang].footer_made;
  }
}

// ========== MENU MOBILE ==========
const mobileMenuBtn = document.querySelector('.mobile-menu-btn');
const navMenu = document.querySelector('.nav-menu');

if (mobileMenuBtn && navMenu) {
  const setMenuOpen = (open) => {
    navMenu.classList.toggle('active', open);
    mobileMenuBtn.textContent = open ? '✕' : '☰';
    mobileMenuBtn.setAttribute('aria-expanded', String(open));
  };

  mobileMenuBtn.addEventListener('click', () => {
    setMenuOpen(!navMenu.classList.contains('active'));
  });

  navMenu.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => setMenuOpen(false));
  });

  // Fecha o menu ao voltar para o layout desktop
  window.matchMedia('(min-width: 961px)').addEventListener('change', (e) => {
    if (e.matches) setMenuOpen(false);
  });
}

// ========== SELETOR DE IDIOMA ==========
document.querySelectorAll('.lang-option').forEach((btn) => {
  btn.addEventListener('click', () => {
    currentLang = btn.dataset.lang;
    updateLanguage();
    try {
      localStorage.setItem('preferred_language', currentLang);
    } catch (e) {}
  });
});

// Carregar idioma salvo
let savedLang = null;
try {
  savedLang = localStorage.getItem('preferred_language');
} catch (e) {}
if (savedLang && translations[savedLang]) {
  currentLang = savedLang;
  updateLanguage();
}

// ========== SMOOTH SCROLL ==========
document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
  anchor.addEventListener('click', function (e) {
    e.preventDefault();
    const target = document.querySelector(this.getAttribute('href'));
    if (target) {
      target.scrollIntoView({ behavior: 'smooth' });
    }
  });
});

// ========== ANIMAÇÃO DE ENTRADA ==========
const observerOptions = {
  threshold: 0.1,
  rootMargin: '0px 0px -50px 0px',
};

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.style.opacity = '1';
      entry.target.style.transform = 'translateY(0)';
      observer.unobserve(entry.target);
    }
  });
}, observerOptions);

document.querySelectorAll('.projeto-card, .skill-category, .timeline-item').forEach((el) => {
  el.style.opacity = '0';
  el.style.transform = 'translateY(30px)';
  el.style.transition = 'all 0.6s ease-out';
  observer.observe(el);
});

